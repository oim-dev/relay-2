/**
 * Проверяемая сквозными маршрутами часть статуса одного проекта.
 * Транспортные подробности и остальные диагностические поля не закрепляются снимком JSON.
 */
export interface GitSyncStatusResult {
  /* Выбранный пользователем режим сетевого обмена проекта. */
  readonly mode: "manual" | "auto";
  /* Фактическая наблюдаемость отдельного процесса, не результат последнего обмена. */
  readonly worker: {
    /* Сохранённое желание пользователя запускать либо останавливать worker. */
    readonly desired: "running" | "stopped";
    /* Подтверждённое состояние; unknown не считается живым worker. */
    readonly actual: "running" | "stopped" | "unknown";
    /* Подтверждение отзывчивости через рабочий протокол. */
    readonly responsive: boolean;
    /* Непустой ID конкретного запуска либо null при отсутствии регистрации готовности. */
    readonly instance: string | null;
  };
  /* Сохранённая диагностика конфликтов выбранной реплики. */
  readonly conflicts: {
    /* Неотрицательное целое количество неразрешённых конфликтов. */
    readonly count: number;
  };
  /* Время назначенного повтора либо null, если повтор не запланирован. */
  readonly nextRetry: string | null;
}
