/**
 * Потоки встраиваемого запуска CLI; приложению принадлежат запись и обработка ошибок потоков.
 */
export interface CliOutput {
  /* Получатель успешного результата или справки; вызывается с завершающим LF. */
  readonly stdout: (text: string) => void;
  /* Получатель диагностики; успешный вызов в него не пишет. */
  readonly stderr: (text: string) => void;
}
