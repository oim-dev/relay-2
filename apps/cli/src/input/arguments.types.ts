/**
 * Поля на границе CLI: имена и источники уже проверены, предметные значения проверяет Core.
 * Отсутствующее свойство отличается от явных null, false и пустой строки.
 */
export type InputFields = Record<string, unknown>;

/**
 * Значения параметров после разбора Gunshi, включая глобальные и позиционные аргументы.
 * CLI читает их без изменения; преобразованные поля складываются в отдельный объект.
 */
export type ArgumentValues = Readonly<Record<string, unknown>>;
