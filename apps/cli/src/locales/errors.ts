/**
 * Тексты внешней границы ошибок CLI и процессных потоков.
 */
export const errorMessages = {
  unknown: "Неизвестная ошибка",
  /**
   * Направляет к справке самого глубокого распознанного узла команды.
   */
  help: (command: string): string => `Справка: ${command}\n`,

  /**
   * Объясняет разбор отдельного dash-leading текста и способ передать те же байты значения.
   */
  dashValue: (name: string): string =>
    `Аргумент после --${name} начинается с «-» и разобран как параметры.\nЕсли это значение --${name}, соедините --${name}= с исходным текстом в shell-кавычках без пробела после «=»; текст оставьте без изменений.`,

  /**
   * Оформляет стабильный код и уже очищенное сообщение в текстовую диагностику.
   */
  failure: (code: string, message: string): string => `Ошибка: ${code}: ${message}\n`,
} as const;
