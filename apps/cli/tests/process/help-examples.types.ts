/**
 * Вызов из показанного примера, разобранный настоящей оболочкой без выполнения Relay.
 */
export interface HelpExampleCall {
  /* Индекс маршрута справки в исходной таблице; сохраняет связь примера с владельцем. */
  readonly route: number;
  /* Точные аргументы после имени relay, включая многострочные значения. */
  readonly argv: readonly string[];
}

/**
 * Распознанный парсером пример: исполнение действия остановлено, справка или версия отрисованы.
 */
export interface ValidatedHelpExample {
  /* Канонический путь команды, без пользовательских позиционных значений. */
  readonly path: string;
  /* Парсер выбрал --help или --version; такой пример не заменяет пример выполнения действия. */
  readonly informational: boolean;
}
