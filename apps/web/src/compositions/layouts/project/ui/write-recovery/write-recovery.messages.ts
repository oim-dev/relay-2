/**
 * Подписи явной проверки неопределённой записи проекта.
 */
export const writeRecoveryMessages = {
  action: "Проверить первоначальную запись",
  message:
    "Ответ сохранения не получен. Проверьте первоначальную операцию, даже если её редактор уже закрыт. Новый ввод не будет отправлен этой проверкой.",
  confirmed: "Первоначальная запись подтверждена",
  /**
   * Сохраняет видимую область достоверного отказа при последующих переходах между проектами.
   */
  rejected(projectName: string): string {
    return `Первоначальная запись отклонена · ${projectName}`;
  },
  /**
   * Указывает область восстановления, даже если исходный редактор закрыт.
   */
  title(projectName: string): string {
    return `Проверка сохранения · ${projectName}`;
  },
};
