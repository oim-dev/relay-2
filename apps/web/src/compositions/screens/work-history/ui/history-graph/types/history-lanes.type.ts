/** Одна вертикальная дорожка всего показанного участка ветки. */
export type HistoryLaneReservation = {
  /** Постоянная колонка всех точек и якорей этой ветки. */
  column: number;
  /** Цвет закреплён за веткой, не за переиспользованным слотом. */
  colorIndex: number;
  /** Первая визуальная подстрока, включая присоединения дочерних веток. */
  first: number;
  /** Конец собственного участка либо строка над работой потомков; не бесконечный резерв. */
  last: number;
};

/** Дорожки веток и их присутствие на строках событий. */
export type HistoryLaneLayout = {
  /** Реальные интервалы и неизменные цвета веток. */
  lanes: Map<string, HistoryLaneReservation>;
  /** Строка → ветка → слот справа от оси (ось всегда 0). */
  columns: Map<number, Map<string, number>>;
};
