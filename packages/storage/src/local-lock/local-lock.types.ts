/**
 * Параметры отдельного межпроцессного mutex, удерживаемого через await вызывающего.
 */
export interface LocalLockOptions {
  /* Ожидание занятости в миллисекундах, 0..300000; по умолчанию 0 — немедленный отказ. */
  readonly timeoutMs?: number;
}

/**
 * Владение отдельным SQLite lock-файлом, не предметной транзакцией проекта.
 * release обязателен в finally; при аварии процесс освобождается механизмом ОС.
 */
export interface LocalLock {
  /**
   * Освобождает соединение и mutex; повтор безопасен, файл не удаляется.
   */
  release(): void;
}
