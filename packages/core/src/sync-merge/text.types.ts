/**
 * Точный результат объединения текста; отказ не содержит частичного текста или маркеров.
 */
export type TextMergeResult =
  | {
      /* Обе версии согласованы относительно общего предка. */
      readonly ok: true;
      /* Полный текст без нормализации UTF-16, пробелов и переводов строк. */
      readonly text: string;
    }
  | {
      /* Правки несовместимы либо исчерпан документированный бюджет расчёта. */
      readonly ok: false;
    };

/**
 * Замена полуоткрытого диапазона исходной строки; пустой диапазон обозначает вставку.
 */
export interface TextHunk {
  /* Начало заменяемого диапазона в кодовых единицах UTF-16. */
  readonly start: number;
  /* Конец заменяемого диапазона в кодовых единицах UTF-16, исключительно. */
  readonly end: number;
  /* Точное содержимое замены; пустая строка означает удаление. */
  readonly text: string;
}

/**
 * Правка с происхождением для сборки пересекающихся блоков двух версий.
 */
export interface SidedTextHunk extends TextHunk {
  /* Версия, чей diff содержит правку. */
  readonly side: "local" | "remote";
}

/**
 * Токены одной строки; числовые ключи сравнимы только в пределах общего словаря.
 */
export interface TextTokens {
  /* Исходная строка без преобразований. */
  readonly text: string;
  /* Ключи точных строковых токенов в порядке появления. */
  readonly keys: readonly number[];
  /* Начала токенов и конечный sentinel text.length; длина на один больше keys. */
  readonly offsets: readonly number[];
}

/**
 * Диапазоны одной элементарной вставки или удаления в координатах токенов.
 */
export interface TokenEdit {
  /* Начало диапазона токенов base, включительно. */
  readonly start: number;
  /* Конец диапазона токенов base, исключительно. */
  readonly end: number;
  /* Начало диапазона токенов новой версии, включительно. */
  readonly nextStart: number;
  /* Конец диапазона токенов новой версии, исключительно. */
  readonly nextEnd: number;
}

/**
 * Общий расходуемый бюджет одного вызова mergeText, принадлежащий только этому расчёту.
 * Внутренние шаги уменьшают счётчики; вызывающая сторона не передаёт этот объект.
 */
export interface TextDiffBudget {
  /* Оставшиеся состояния Myers и сравнения токенов на всех уровнях diff. */
  steps: number;
  /* Оставшиеся ячейки Int32Array всех таблиц восстановления пути. */
  traceCells: number;
}

/**
 * Гранулярность diff: полные строки либо неделимые слова и пробельные промежутки.
 */
export type TextTokenMode = "lines" | "words";
