/**
 * Дополнительные ограничения текста после проверки строкового типа на границе данных.
 */
export interface TaskTextOptions {
  /* При true запрещает все поддерживаемые разделители строк; по умолчанию false. */
  readonly singleLine?: boolean;
  /* При true требует непустой текст после trim; исходная строка не изменяется. */
  readonly required?: boolean;
}

/**
 * Первое нарушение текста: длина или NUL, затем однострочность, затем обязательность.
 * Код и сообщение ошибки выбирает граница внешнего ввода либо сохранённой карточки.
 */
export type TaskTextViolation = "format" | "singleLine" | "required";
