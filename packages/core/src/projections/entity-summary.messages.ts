/**
 * Диагностики повреждённых полей краткого предметного чтения.
 */
export const entitySummaryMessages = {
  /**
   * Называет запись и неверное выбранное поле без подстановки отсутствующего содержания.
   */
  invalidField: (key: string, field: string): string =>
    `Запись ${key} содержит некорректное поле краткого представления: ${field}.`,
} as const;
