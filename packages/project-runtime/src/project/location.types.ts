import type { ProjectDatabase } from "@relay/storage";

/**
 * Расположение проекта после проверки конфигурации и соответствия постоянного ID базе.
 * Само расположение не владеет соединением; его жизненный цикл определяет вернувшая его операция.
 */
export interface ProjectLocation {
  /* Постоянный ID проекта, совпадающий в конфигурации и SQLite. */
  projectId: string;
  /* Абсолютный путь SQLite: стандартный внутри home либо явно переопределённый в конфиге. */
  databasePath: string;
  /* Абсолютный путь выбранного конфига; явная символьная ссылка сохраняется. */
  configPath: string;
}

/**
 * Проверенный проект с единственным открытым рабочим соединением, переданным вызывающему.
 * Получатель обязан закрыть database в finally. Снимок или транзакцию он выбирает отдельно.
 */
export interface OpenedProject {
  /* Выбранный конфиг, абсолютный путь и ID, сверенный с этим же соединением. */
  readonly location: ProjectLocation;
  /* Открытая совместимая база; Runtime не закрывает её после успешной передачи владельцу. */
  readonly database: ProjectDatabase;
}
