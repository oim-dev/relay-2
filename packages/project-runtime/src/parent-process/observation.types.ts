/**
 * Нативное наблюдение конкретного непосредственного родителя без права завершать его.
 * Контекст захватывается один раз; проверка не открывает процесс заново по сохранённому PID.
 */
export interface ParentProcessProbe {
  /* Проверяет исходного родителя; false терминален, неожиданный отказ наблюдения выбрасывает ошибку. */
  readonly isAlive: () => boolean;
  /* Идемпотентно освобождает удержанные native-ресурсы, не посылая сигналов процессам. */
  readonly dispose: () => void;
}

/**
 * Наблюдение lifetime родителя. Само не удерживает event loop и не останавливает дочерние команды.
 */
export interface ParentProcessObservation {
  /* Отмена с "parent-exited" при потере родителя либо с RelayError при отказе наблюдения/освобождения. */
  readonly signal: AbortSignal;
  /* Снимает наблюдение без отмены signal; повтор безопасен, ошибка освобождения остаётся явной. */
  readonly dispose: () => void;
}
