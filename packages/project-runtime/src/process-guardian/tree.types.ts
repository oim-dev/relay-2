/**
 * Владение отдельным контейнером до запуска команды внутри уже созданного якоря.
 * Граница удержания задана capability выбранного ProcessLifetime; macOS process group
 * не обещает удерживать произвольных потомков, самостоятельно сменивших сессию.
 */
export interface CommandTree {
  /**
   * Принудительно завершает всех участников контейнера, включая живой якорь.
   */
  terminate(): Promise<void>;
  /**
   * Закрывает нативные ресурсы контейнера после подтверждения завершения потоков.
   */
  dispose(): void;
}
