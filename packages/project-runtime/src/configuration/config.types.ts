/**
 * Локальная регистрация проекта в workspace; форма записи не гарантирует доступность проекта.
 */
export interface ProjectRegistration {
  /* Уникальное в workspace непустое имя без пробелов по краям и нулевого символа. */
  name: string;
  /* Абсолютный путь каталога проекта; наличие relay.config.json и базы проверяется при выборе. */
  path: string;
}

/**
 * Проверенная конфигурация проекта первой версии; путь базы уже сделан абсолютным.
 */
export interface ProjectConfig {
  /* Поддерживаемая версия локального формата конфигурации. */
  readonly version: 1;
  /* Постоянный ID проекта; соответствие базе проверяется отдельно при открытии. */
  readonly projectId: string;
  /* Абсолютный путь базы относительно физического каталога конфигурации. */
  readonly databasePath: string;
}

/**
 * Проверенный снимок workspace; имена уникальны, порядок совпадает с файлом.
 * Проверка формы не открывает зарегистрированные конфиги и базы.
 */
export interface WorkspaceConfig {
  /* Поддерживаемая версия локального формата конфигурации. */
  readonly version: 1;
  /* Регистрации в порядке добавления; пустой массив означает пустой workspace. */
  readonly projects: ProjectRegistration[];
}
