/**
 * Явный локальный контекст вызова Runtime; окружение процесса читает вызывающая CLI.
 * Относительные home и config разрешаются от cwd, выбор проекта выполняется по имени регистрации.
 */
export interface RuntimeOptions {
  /* Рабочий каталог вызова; непустой путь без нулевого символа. */
  readonly cwd: string;
  /* Корень локальных баз; при отсутствии используется homedir()/.relay. */
  readonly home?: string;
  /* Явный путь конфигурации; при отсутствии выполняется поиск вверх от cwd. */
  readonly config?: string;
  /* Имя регистрации для выбора проекта из workspace; регистрации по умолчанию нет. */
  readonly project?: string;
}
