import type { EntityData, EntityRecord } from "../entities/entity.types";
import type { TASK_COLUMNS } from "./tasks.constants";

/**
 * Колонка задачи из общего перечня TASK_COLUMNS.
 */
export type TaskColumn = (typeof TASK_COLUMNS)[number];

/**
 * Критерий приёмки в составе содержания задачи.
 * Отметка выполнения и её автор изменяются под ревизией самой задачи.
 */
export interface TaskCriterion {
  /* Постоянный ID критерия внутри задачи, сохраняемый при правке и перестановке. */
  id: string;
  /* Краткий непустой заголовок критерия. */
  title: string;
  /* Краткое пояснение; пустая строка означает отсутствие пояснения. */
  summary: string;
  /* Подробное описание; пустая строка допустима. */
  description: string;
  /* Признак выполнения собственного критерия, независимо от состояния дочерних задач. */
  completed: boolean;
  /* Время отметки выполнения в ISO 8601; null у невыполненного критерия. */
  completedAt: string | null;
  /* Автор отметки выполнения; null у невыполненного критерия. */
  completedBy: string | null;
}

/**
 * Поля неизменяемой записи отдельного журнала комментариев задачи.
 */
interface TaskCommentFields {
  /* Постоянный ID комментария в журнале задачи. */
  id: string;
  /* Заголовок комментария; пустая строка означает отсутствие заголовка. */
  title: string;
  /* Основной текст комментария. */
  body: string;
  /* Время добавления комментария в ISO 8601. */
  createdAt: string;
  /* Автор комментария, проверенный через validateActor. */
  createdBy: string;
}

/**
 * Комментарий для добавления в журнал или чтения его проекции.
 * Совместим с JSON-контрактом журнала; добавление не меняет ревизию содержания задачи.
 */
export type TaskComment = EntityData<TaskCommentFields>;

/**
 * Поля декодированной задачи со связями по постоянным ID.
 * Массивы связей не содержат повторов; Core проверяет граф обязательств отдельно.
 */
interface TaskFields {
  /* Постоянный ID доски, определяющей адрес и допустимые цели задачи. */
  boardId: string;
  /* Однострочный заголовок; при создании без названия сохраняется пустая строка. */
  title: string;
  /* Подробное описание; пустая строка допустима. */
  description: string;
  /* Текущая колонка из TASK_COLUMNS. */
  column: TaskColumn;
  /* Постоянный ID родительской задачи; null означает корневую задачу. */
  parentId: string | null;
  /* Постоянные ID задач, от завершения которых зависит эта задача. */
  dependencies: string[];
  /* Постоянные ID связанных задач, не образующих обязательств завершения. */
  related: string[];
  /* Постоянные ID предметных целей задачи; набор зависит от её доски. */
  targets: string[];
  /* Собственные критерии приёмки в пользовательском порядке. */
  acceptanceCriteria: TaskCriterion[];
  /* Проекция отдельного append-only журнала, не часть ревизии содержания задачи. */
  comments: TaskComment[];
}

/**
 * Содержимое задачи, совместимое с сырой записью хранения через EntityData.
 * Изменяемые поля позволяют Core подготовить черновик до атомарного сохранения.
 */
export type TaskData = EntityData<TaskFields>;

/**
 * Декодированная запись задачи с содержимым и проекцией журнала комментариев.
 */
export interface TaskRecord extends Omit<EntityRecord, "kind" | "data"> {
  /* Дискриминатор записи задачи. */
  kind: "task";
  /* Проверенное содержание и независимая проекция комментариев. */
  data: TaskData;
}

/**
 * Вычисленная готовность задачи по собственным критериям, детям и зависимостям.
 * Отменённая задача не считается выполненной; детали правила принадлежат графу Core.
 */
export interface TaskProgress {
  /* Фактическая выполненность задачи вместе с её обязательствами. */
  completed: boolean;
  /* Возможность перейти в done с учётом текущих обязательств. */
  canComplete: boolean;
  /* Постоянные ID невыполненных прямых детей и зависимостей, без повторов. */
  blockers: string[];
}
