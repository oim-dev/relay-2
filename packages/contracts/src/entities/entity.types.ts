import type { EntityKind } from "./identity.types";

/**
 * Сырая запись локального хранилища до предметного декодирования в Core.
 * Ревизия относится к содержанию сущности; журнал комментариев задачи независим.
 * Поля остаются изменяемыми для подготовки транзакционных черновиков.
 */
export interface EntityRecord {
  /* Постоянный ID сущности в проекте; структурированные связи сохраняют именно его. */
  id: string;
  /* Вид записи, по которому Core выбирает проверку содержимого data. */
  kind: EntityKind;
  /* Текущий читаемый ключ сущности в проекте; прежний ключ может стать алиасом. */
  key: string;
  /* Положительная целая ревизия содержания, используемая при конкурентной записи. */
  revision: number;
  /* Время создания записи в формате ISO 8601. */
  createdAt: string;
  /* Время последнего изменения содержания в формате ISO 8601. */
  updatedAt: string;
  /* Автор создания, дословно сохранённый после validateActor. */
  createdBy: string;
  /* Автор последнего изменения содержания, проверенный через validateActor. */
  updatedBy: string;
  /* Сырой JSON-объект; форму конкретного вида подтверждает предметный декодер Core. */
  data: Record<string, unknown>;
}

/**
 * Идентичность разрешённой ссылки без загрузки содержания и журнала комментариев.
 */
export type EntityIdentity = Pick<EntityRecord, "id" | "kind" | "key">;

/**
 * Параметры конкурентного изменения содержания.
 * Предметный сценарий определяет владельца ревизии и проверяет её до no-op.
 */
export interface WriteOptions {
  /* Автор операции; правила допустимого значения принадлежат validateActor. */
  readonly actor: string;
  /* Ожидаемая положительная целая ревизия владельца изменяемого содержания. */
  readonly ifRevision: number;
}

/**
 * Сохраняет закрытую схему данных совместимой с сырым JSON-контрактом EntityRecord.
 * Производный объектный тип, в отличие от интерфейса с declaration merging,
 * присваивается Record<string, unknown> без открытой индексной сигнатуры.
 * Поля и варианты объединений выводятся из схемы, их изменяемость сохраняется.
 */
export type EntityData<Fields extends object> = { [Field in keyof Fields]: Fields[Field] };
