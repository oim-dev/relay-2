import type { EntityData, EntityRecord } from "../entities/entity.types";
import type { PLAN_SCOPE_KINDS, PLAN_STATUSES, RELEASE_STATUSES } from "./planning.constants";
import type { TaskRecord } from "../tasks/tasks.types";

/**
 * Вид сущности планирования, определяющий её жизненный цикл и состав.
 */
export type PlanningKind = "work-plan" | "release";

/**
 * Состояние рабочего плана из PLAN_STATUSES.
 */
export type PlanStatus = (typeof PLAN_STATUSES)[number];

/**
 * Состояние релиза из RELEASE_STATUSES.
 */
export type ReleaseStatus = (typeof RELEASE_STATUSES)[number];

/**
 * Одна предметная цель в области рабочего плана.
 * В сохранённых данных id уже разрешён в постоянный ID; ввод допускает ссылку.
 */
export interface PlanScope {
  /* Вид цели из PLAN_SCOPE_KINDS, используемый при разрешении ссылки. */
  kind: (typeof PLAN_SCOPE_KINDS)[number];
  /* Постоянный ID сохранённой цели либо пользовательская ссылка во входных полях. */
  id: string;
}

/**
 * Этап рабочего плана с упорядоченным составом задач.
 * Собственной ревизии нет: этап и его состав принадлежат ревизии плана.
 */
export interface PlanStage {
  /* Постоянный ID этапа внутри плана. */
  id: string;
  /* Непустой однострочный заголовок этапа. */
  title: string;
  /* Краткое описание; пустая строка допустима. */
  summary: string;
  /* Ожидаемый итог этапа; пустая строка означает отсутствие описания. */
  outcome: string;
  /* Текстовые условия завершения; не заменяют вычисление готовности задач. */
  completionConditions: string;
  /* Постоянные ID задач в пользовательском порядке; задача входит в план не более одного раза. */
  taskIds: string[];
}

/**
 * Редактируемые поля содержания плана без состояния и состава этапов.
 * Во входе scope может содержать ссылки; Core разрешает их перед сохранением.
 */
export interface WorkPlanFields {
  /* Непустой однострочный заголовок плана. */
  title: string;
  /* Краткое описание; при создании по умолчанию пустая строка. */
  summary: string;
  /* Цель работы; при создании по умолчанию пустая строка. */
  goal: string;
  /* Обоснование работы; при создании по умолчанию пустая строка. */
  rationale: string;
  /* Границы и исключения работы; при создании по умолчанию пустая строка. */
  boundaries: string;
  /* Ожидаемый итог всего плана; при создании по умолчанию пустая строка. */
  expectedResult: string;
  /* Имена участников без повторов; пустой массив означает, что участники не указаны. */
  participants: string[];
  /* Предметные цели без повторов ID; пустой массив означает, что область не задана. */
  scope: PlanScope[];
}

/**
 * Редактируемые поля релиза, включая упорядоченный состав планов.
 * При вводе planIds допускает ссылки; сохранённый состав содержит постоянные ID.
 */
export interface ReleaseFields {
  /* Непустой однострочный заголовок релиза. */
  title: string;
  /* Непустая однострочная версия; семантическое версионирование не требуется. */
  version: string;
  /* Краткое описание; при создании по умолчанию пустая строка. */
  summary: string;
  /* Подробное описание; при создании по умолчанию пустая строка. */
  description: string;
  /* Непустой упорядоченный состав планов без повторов, после сохранения — постоянные ID. */
  planIds: string[];
  /* Календарная дата YYYY-MM-DD; пустая строка означает отсутствие плановой даты. */
  plannedFor: string;
}

/**
 * Полная схема содержания плана после разрешения ссылок и проверки состояния.
 */
interface WorkPlanStoredFields extends WorkPlanFields {
  /* Постоянный ID локального проекта-владельца плана. */
  projectId: string;
  /* Этапы в пользовательском порядке; пустой план допустим до завершения. */
  stages: PlanStage[];
  /* Итог закрытия плана; до закрытия пустая строка. */
  result: string;
  /* Текущее состояние из PLAN_STATUSES. */
  status: PlanStatus;
  /* Время начала в ISO 8601; null, если план ещё не запускался. */
  startedAt: string | null;
  /* Время завершения или отмены в ISO 8601; null у незакрытого плана. */
  closedAt: string | null;
}

/**
 * Содержимое плана, изменяемое Core как транзакционный черновик.
 * EntityData сохраняет совместимость с JSON-контрактом EntityRecord.
 */
export type WorkPlanData = EntityData<WorkPlanStoredFields>;

/**
 * Полная схема содержания релиза после разрешения состава и проверки состояния.
 */
interface ReleaseStoredFields extends ReleaseFields {
  /* Постоянный ID локального проекта-владельца релиза. */
  projectId: string;
  /* Текущее состояние из RELEASE_STATUSES. */
  status: ReleaseStatus;
  /* Время публикации в ISO 8601; null у неопубликованного релиза. */
  releasedAt: string | null;
  /* Автор публикации; null у неопубликованного релиза. */
  releasedBy: string | null;
}

/**
 * Содержимое релиза, совместимое с JSON-контрактом EntityRecord.
 */
export type ReleaseData = EntityData<ReleaseStoredFields>;

/**
 * Декодированная запись рабочего плана; ревизия охватывает этапы и состав задач.
 */
export interface WorkPlanRecord extends Omit<EntityRecord, "kind" | "data"> {
  /* Дискриминатор рабочего плана. */
  kind: "work-plan";
  /* Проверенное содержание плана с разрешёнными связями. */
  data: WorkPlanData;
}

/**
 * Декодированная запись релиза; ревизия охватывает его собственный состав планов.
 */
export interface ReleaseRecord extends Omit<EntityRecord, "kind" | "data"> {
  /* Дискриминатор релиза. */
  kind: "release";
  /* Проверенное содержание релиза с разрешённым составом. */
  data: ReleaseData;
}

/**
 * Запись планирования с формой содержания, определяемой kind.
 */
export type PlanningRecord = WorkPlanRecord | ReleaseRecord;

/**
 * Адрес и ревизия плана-владельца этапов и включений задач.
 */
export interface PlanOwner {
  /* Текущий читаемый ключ плана. */
  plan: string;
  /* Ревизия содержания плана, пригодная для изменения этапа или его состава. */
  revision: number;
}

/**
 * Этапы и ревизия плана, полученные из одного согласованного снимка.
 */
export interface PlanStages extends PlanOwner {
  /* Этапы в пользовательском порядке; пустой массив означает план без этапов. */
  items: PlanStage[];
}

/**
 * Один этап с адресом и ревизией владеющего им плана.
 */
export interface PlanStageResult extends PlanOwner {
  /* Этап из того же снимка, которому принадлежит revision. */
  stage: PlanStage;
}

/**
 * Полные карточки задач этапа и ревизия состава плана из одного снимка.
 */
export interface PlanStageTasks extends PlanOwner {
  /* Задачи в порядке включения в этап; у каждой собственная ревизия содержания. */
  items: TaskRecord[];
}

/**
 * Текущие и исторические включения задачи в планы из одного снимка.
 */
export interface TaskPlanMemberships {
  /* Текущий читаемый ключ задачи, для которой найдены включения. */
  task: string;
  /* Этапы с ревизиями их планов; пустой массив означает отсутствие включений. */
  items: PlanStageResult[];
}

/**
 * Состав релиза из одного снимка; вложенные планы имеют собственные ревизии.
 */
export interface ReleasePlans {
  /* Текущий читаемый ключ релиза-владельца состава. */
  release: string;
  /* Ревизия содержания релиза, защищающая его состав планов. */
  revision: number;
  /* Полные карточки планов в порядке их включения в релиз. */
  items: WorkPlanRecord[];
}

/**
 * Состояния обоих планов после атомарного переноса задачи.
 */
export interface PlanTransferResult {
  /* Исходный план после удаления включения задачи. */
  source: WorkPlanRecord;
  /* Целевой план после добавления задачи в выбранный этап. */
  target: WorkPlanRecord;
}

/**
 * Счётчики готовности задач либо планов, в зависимости от владельца результата.
 */
export interface ProgressCounts {
  /* Общее число включённых элементов. */
  total: number;
  /* Число фактически выполненных элементов. */
  completed: number;
  /* Целый процент 0..100 с округлением вниз; при total=0 равен нулю. */
  percent: number;
}

/**
 * Готовность этапа по текущему графу его задач; пустой этап не считается выполненным.
 */
interface PlanStageProgress {
  /* Постоянный ID этапа внутри плана. */
  id: string;
  /* Непустой состав этапа полностью выполнен. */
  completed: boolean;
  /* Счётчики включённых задач этапа. */
  counts: ProgressCounts;
  /* ID невыполненных задач и их блокирующих обязательств без повторов. */
  blockers: string[];
}

/**
 * Текущая готовность плана по задачам всех этапов, независимо от статуса плана.
 * Пустой этап не блокирует непустой выполненный план; полностью пустой план не готов.
 */
export interface PlanProgress {
  /* Непустой состав задач плана полностью выполнен. */
  completed: boolean;
  /* Готовность состава к завершению; допустимость перехода статуса проверяет Core. */
  canComplete: boolean;
  /* ID невыполненных задач и обязательств; у пустого плана единственный элемент — ID плана. */
  blockers: string[];
  /* Счётчики задач по всем этапам плана. */
  counts: ProgressCounts;
  /* Готовность этапов в порядке их расположения в плане. */
  stages: PlanStageProgress[];
}

/**
 * Готовность одного плана в релизе с учётом его статуса и актуального графа задач.
 */
interface ReleasePlanProgress {
  /* Постоянный ID плана, включённого в релиз. */
  id: string;
  /* Текущий статус включённого плана. */
  status: PlanStatus;
  /* План имеет статус completed и фактически выполненный состав задач. */
  completed: boolean;
  /* ID неготового плана и его блокирующих задач без повторов; у готового плана пусто. */
  blockers: string[];
}

/**
 * Текущая готовность состава релиза; публикация не замораживает состояние задач.
 */
export interface ReleaseProgress {
  /* Непустой состав релиза содержит только завершённые и фактически готовые планы. */
  completed: boolean;
  /* Готовность состава к публикации; допустимость перехода статуса проверяет Core. */
  canRelease: boolean;
  /* ID неготовых планов и блокирующих задач без повторов. */
  blockers: string[];
  /* Счётчики готовности включённых планов, а не их задач. */
  counts: ProgressCounts;
  /* Готовность планов в порядке их включения в релиз. */
  plans: ReleasePlanProgress[];
}
